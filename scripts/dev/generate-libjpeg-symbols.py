"""Regenerate the private symbol header after updating vendored libjpeg-turbo.

Every libjpeg-turbo global (jpeg*, j12*/j16*, jinit_*, jcopy_*, jsimd_* and the few helpers
below) gets a patchy_ljt_ prefix, so the JPEG library Qt's image plug-in loads (or links
statically, in the browser build) never interposes on Patchy's decode-only copy or the
reverse. Names the public headers #define (jpeg_create_decompress and the like) are left
alone; they expand to prefixed names. Audit the built archive's defined globals after
upgrades (llvm-nm or dumpbin /symbols): nothing may stay unprefixed.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
dest = root / "src/formats/libjpeg-turbo/src"
public_headers = ("jpeglib.h", "jmorecfg.h", "jerror.h", "jconfig.h.in")

pattern = re.compile(r"\b(?:_?jpeg\w*|j12\w+|j16\w+|jinit_\w+|jcopy_\w+|jsimd_\w+|jdiv_round_up|jround_up|jzero_far)\b")
names = set()
for path in sorted(dest.rglob("*")):
    if path.suffix in (".h", ".c", ".in"):
        names.update(pattern.findall(path.read_text(encoding="utf-8", errors="replace")))
macros = set()
for header in public_headers:
    source = (dest / header).read_text(encoding="utf-8", errors="replace")
    macros.update(re.findall(r"^\s*#\s*define\s+(\w+)", source, re.M))
names.difference_update(macros)
# Words from comments and token-pasted stems, not identifiers; _jpeg_* are jsamplecomp.h's
# per-precision aliases, which expand to prefixed names.
junk = {"jpeg", "jpegint", "jpeglib", "jpegapicomp", "jpeg_get", "jpeg_create_xxx"}
names = {name for name in names if name not in junk and not name.startswith("_") and not name.endswith("_")}
header = """/* Private libjpeg-turbo 3.1.4.1 symbols.
 * Generated by scripts/dev/generate-libjpeg-symbols.py. Do not edit manually. */
#ifndef PATCHY_LIBJPEG_SYMBOLS_H
#define PATCHY_LIBJPEG_SYMBOLS_H

"""
header += "".join(f"#define {name} patchy_ljt_{name}\n" for name in sorted(names))
header += "\n#endif\n"
(root / "src/formats/libjpeg-turbo/patchy_libjpeg_symbols.h").write_text(header, encoding="utf-8", newline="\n")
