"""Writes every benchmark page variant as a PNG (the same pixels bench_ppocr.py reads), plus
bench_windows.js, a Patchy script that reads them with the Windows engine.

    python -I make_variants.py <pages-dir>
"""
import json
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bench_ppocr  # noqa: E402

VARIANTS = ["clean300", "scan300", "clean150", "scan150"]
# The recognizer languages this PC's Windows has; other pages are skipped.
WINDOWS_LANGUAGE = {"en": "en-US", "latin": "en-US", "ja": "ja"}


def main() -> int:
    pages_dir = Path(sys.argv[1])
    out = pages_dir / "variants"
    out.mkdir(exist_ok=True)
    described = json.loads((pages_dir / "pages.json").read_text(encoding="utf-8"))["pages"]
    jobs = []
    for index, page in enumerate(described):
        image = cv2.imdecode(np.fromfile(str(pages_dir / (page["name"] + ".png")), dtype=np.uint8), cv2.IMREAD_COLOR)
        for name in VARIANTS:
            pixels = bench_ppocr.variant(image, name, seed=1000 + index)
            path = out / f'{page["name"]}.{name}.png'
            cv2.imencode(".png", pixels)[1].tofile(str(path))
            if page["language"] in WINDOWS_LANGUAGE:
                jobs.append({"page": page["name"], "variant": name, "language": WINDOWS_LANGUAGE[page["language"]],
                             "path": str(path).replace("\\", "/")})
    script = [
        "// Generated by make_variants.py: reads every page variant with the Windows engine.",
        "var jobs = " + json.dumps(jobs) + ";",
        "for (var i = 0; i < jobs.length; i++) {",
        "  var job = jobs[i];",
        "  var doc = app.open(job.path);",
        "  var started = Date.now();",
        "  var result = doc.recognizeText({engine: 'windows', language: job.language});",
        "  var ms = Date.now() - started;",
        "  var vertical = 0;",
        "  for (var k = 0; k < result.lines.length; k++) { if (result.lines[k].vertical) vertical++; }",
        "  console.log('RESULT ' + JSON.stringify({page: job.page, variant: job.variant, ms: ms,",
        "      lines: result.lines.length, vertical: vertical, text: result.text}));",
        "  doc.close();",
        "}",
        "patchy.setResult({jobs: jobs.length});",
    ]
    (pages_dir / "bench_windows.js").write_text("\n".join(script) + "\n", encoding="utf-8")
    print(len(jobs), "Windows jobs;", len(described) * len(VARIANTS), "variant images")
    return 0


if __name__ == "__main__":
    sys.exit(main())
